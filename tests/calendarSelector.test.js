test("calendar model handles real weekdays, leap centuries and Bahia date boundaries", async () => {
  const { calendarMonth, calendarToday, selectCalendarDate, calendarQueryPeriod, companyCalendarPeriod } = await import("../public/calendar-period-model.mjs");
  assert.equal(calendarMonth(2026, 1).firstWeekday, 4);
  assert.equal(calendarMonth(2026, 2).weeks, 4);
  assert.equal(calendarMonth(2026, 2).days, 28);
  assert.equal(calendarMonth(2026, 8).weeks, 6);
  assert.equal(calendarMonth(2026, 8).firstWeekday, 6);
  assert.equal(calendarMonth(2028, 2).days, 29);
  assert.equal(calendarMonth(1900, 2).days, 28);
  assert.equal(calendarMonth(2000, 2).days, 29);
  assert.equal(calendarMonth(2100, 2).days, 28);
  for (const [year, month] of [[2026, 1], [2026, 8], [2028, 2], [2027, 12]]) {
    const model = calendarMonth(year, month), dates = model.cells.filter(Boolean);
    assert.equal(dates.length, model.days);
    assert.equal(dates[0].day, 1);
    assert.equal(dates.at(-1).day, model.days);
    assert.equal(new Set(dates.map((cell) => cell.date)).size, model.days);
  }
  assert.deepEqual(calendarToday(new Date("2026-11-20T01:30:00Z")), { year: 2026, month: 11, day: 19 });
  assert.throws(() => calendarMonth(2026, 13));
  let period = { year: 2026, month: 11, startDate: null, endDate: null };
  assert.deepEqual(calendarQueryPeriod(period), { year: 2026, month: 11, startDate: "2026-11-01", endDate: "2026-11-30", mode: "month", available: true });
  assert.equal(calendarQueryPeriod(period, "2026-11-19").endDate, "2026-11-19");
  period = selectCalendarDate(period, "2026-11-15");
  period = selectCalendarDate(period, "2026-11-05");
  assert.equal(period.startDate, "2026-11-05"); assert.equal(period.endDate, "2026-11-15");
  period = selectCalendarDate(period, "2026-11-08");
  assert.equal(period.startDate, "2026-11-08"); assert.equal(period.endDate, null);
  period = selectCalendarDate(period, "2026-11-08");
  assert.equal(calendarQueryPeriod(period).mode, "month");
  assert.throws(() => selectCalendarDate(period, "2026-10-31"));
  const now = new Date("2026-11-19T15:00:00Z");
  assert.equal(companyCalendarPeriod(period, null, now).available, true);
  assert.equal(companyCalendarPeriod(period, null, now).processedEndDate, null);
  assert.equal(companyCalendarPeriod(period, { lastCompletedQueryAt: "2026-10-31T15:00:00Z" }, now).lastCompletedDate, "2026-10-31");
  assert.equal(companyCalendarPeriod(period, { lastCompletedQueryAt: "2026-10-31T15:00:00Z" }, now).processedEndDate, null);
  assert.equal(companyCalendarPeriod(period, { lastCompletedQueryAt: "2026-11-20T15:00:00Z" }, now).processedEndDate, null);
  assert.equal(companyCalendarPeriod(period, { lastCompletedQueryAt: "2026-11-18T01:00:00Z" }, now).processedEndDate, "2026-11-17");
  assert.equal(companyCalendarPeriod({ ...period, month: 10 }, null, now).endDate, "2026-10-31");
  const afterLastQuery = companyCalendarPeriod({ ...period, startDate: "2026-11-18", endDate: "2026-11-19" }, { lastCompletedQueryAt: "2026-11-17T15:00:00Z" }, now);
  assert.equal(afterLastQuery.available, true);
  assert.equal(afterLastQuery.startDate, "2026-11-18");
  assert.equal(afterLastQuery.endDate, "2026-11-19");
  assert.equal(afterLastQuery.processedEndDate, null);
});

