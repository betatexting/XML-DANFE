const { createCompanyCatalog, installCompanyRoutes } = require("../src/companyCatalog");
const { installAuth } = require("../src/authRoutes");
const { identifyDownloadedNote, readNoteInventory, installNoteInventoryRoutes } = require("../src/noteInventory");
const a = { id: "a", legalName: "Odonto Marques", cnpj: "14078646000104" };
const b = { id: "b", legalName: "Empresa B", cnpj: "14078646000368" };
const c = { id: "c", legalName: "Sem notas", cnpj: "14078646000449" };
const xml = (cnpj, model = "55") => `<nfeProc><NFe><infNFe><ide><mod>${model}</mod></ide><emit><CNPJ>${cnpj}</CNPJ></emit><dest><CNPJ>${c.cnpj}</CNPJ></dest></infNFe></NFe><protNFe><infProt><cStat>100</cStat></infProt></protNFe></nfeProc>`;
test("inventory lists registered emitters by downloaded type and ignores drafts, summaries and invalid XML", async (t) => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), "note-inventory-"));
  t.after(() => fs.rm(directory, { recursive: true, force: true }));
  await fs.mkdir(path.join(directory, "nested"));
  await fs.writeFile(path.join(directory, "nested", "nfe.xml"), xml(a.cnpj));
  await fs.writeFile(path.join(directory, "nfc.xml"), xml(b.cnpj, "65"));
  await fs.writeFile(path.join(directory, "other.xml"), xml("00000000000000"));
  await fs.writeFile(path.join(directory, "invalid.xml"), "broken");
  const result = await readNoteInventory({ companies: [a, b, c], downloadsDir: directory });
  assert.deepEqual(result.companies.map(({ id, notes }) => ({ id, notes })), [{ id: "a", notes: { nfe: 1, nfs: 0, nfc: 0 } }, { id: "b", notes: { nfe: 0, nfs: 0, nfc: 1 } }]);
  assert.equal(identifyDownloadedNote(xml(a.cnpj).replace("<cStat>100", "<cStat>110")), null);
  assert.equal(identifyDownloadedNote(`<resNFe><CNPJ>${a.cnpj}</CNPJ></resNFe>`), null);
  assert.equal(identifyDownloadedNote(`<Rps><CNPJ>${a.cnpj}</CNPJ></Rps>`), null);
  assert.deepEqual(identifyDownloadedNote(`<CompNfse><Nfse><InfNfse><Numero>1</Numero><PrestadorServico><IdentificacaoPrestador><Cnpj>${a.cnpj}</Cnpj></IdentificacaoPrestador></PrestadorServico></InfNfse></Nfse></CompNfse>`), { cnpj: a.cnpj, type: "nfs" });
  assert.deepEqual(identifyDownloadedNote(`<NFSe><infNFSe><nNFSe>1</nNFSe><emit><CNPJ>${a.cnpj}</CNPJ></emit></infNFSe></NFSe>`), { cnpj: a.cnpj, type: "nfs" });
  await fs.rm(path.join(directory, "nested", "nfe.xml"));
  assert.equal((await readNoteInventory({ companies: [a], downloadsDir: directory })).companies.length, 0);
});

